// Static wiring check: HTML ids vs JS selectors, and Native.* calls vs @JavascriptInterface methods.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const assets = path.join(here, "..", "app", "src", "main", "assets");
const javaDir = path.join(here, "..", "app", "src", "main", "java", "dev", "local", "llmchat");

const html = fs.readFileSync(path.join(assets, "index.html"), "utf8");
const js = fs.readFileSync(path.join(assets, "app.js"), "utf8");
const bridge = fs.readFileSync(path.join(javaDir, "Bridge.java"), "utf8");

let problems = 0;

// ---- ids
const htmlIds = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
const jsIds = new Set([...js.matchAll(/\$\(\s*'#([A-Za-z0-9_-]+)'/g)].map((m) => m[1]));
const dynamicIds = new Set([...js.matchAll(/id="([A-Za-z0-9_-]+)"/g)].map((m) => m[1]));

const staticPrefixes = ["btn-", "page-", "sheet", "scrim", "drawer", "title", "subtitle", "messages", "composer", "input", "attach-row", "toast", "session-list", "model-name"];
const missing = [...jsIds].filter((id) => !htmlIds.has(id) && !dynamicIds.has(id));
if (missing.length) {
  problems += missing.length;
  console.log("MISSING DOM IDS:", missing.join(", "));
} else {
  console.log("PASS every static #id selector exists in index.html or is generated by JS");
}

const unusedHtml = [...htmlIds].filter((id) => !jsIds.has(id));
if (unusedHtml.length) console.log("NOTE ids in HTML not referenced by JS:", unusedHtml.join(", "));

// ---- Native bridge methods
const javaMethods = new Set();
const re = /@JavascriptInterface\s*\n\s*public\s+[\w<>\[\].]+\s+(\w+)\s*\(/g;
let m;
while ((m = re.exec(bridge))) javaMethods.add(m[1]);

const jsCalls = new Set([...js.matchAll(/Native\.(\w+)\s*\(/g)].map((mm) => mm[1]));
const missingNative = [...jsCalls].filter((fn) => !javaMethods.has(fn));
if (missingNative.length) {
  problems += missingNative.length;
  console.log("MISSING NATIVE METHODS:", missingNative.join(", "));
} else {
  console.log("PASS every Native.* call has a @JavascriptInterface method (" + jsCalls.size + " calls)");
}

const unusedJava = [...javaMethods].filter((fn) => !jsCalls.has(fn));
if (unusedJava.length) console.log("NOTE java methods not called from JS:", unusedJava.join(", "));

// ---- bridge callbacks: native emits -> JS handlers
const emitted = new Set([...bridge.matchAll(/emit\("(\w+)"/g)].map((mm) => mm[1]));
const handlers = new Set([...js.matchAll(/^\s{4}(\w+):\s*function\s*\(/gm)].map((mm) => mm[1]));
const missingHandlers = [...emitted].filter((e) => !handlers.has(e));
if (missingHandlers.length) {
  problems += missingHandlers.length;
  console.log("MISSING JS CALLBACKS:", missingHandlers.join(", "));
} else {
  console.log("PASS every emit() target has a window.__bridge handler (" + emitted.size + " events)");
}

// ---- CSS classes used by JS/HTML exist in stylesheet
const css = fs.readFileSync(path.join(assets, "style.css"), "utf8");
const jsClasses = new Set();
for (const mm of js.matchAll(/className\s*=\s*'([^']+)'/g)) {
  mm[1].split(/\s+/).filter(Boolean).forEach((c) => jsClasses.add(c));
}
for (const mm of js.matchAll(/class="([^"]+)"/g)) {
  mm[1].split(/\s+/).filter((c) => c && !c.includes("$")).forEach((c) => jsClasses.add(c));
}
const cssClasses = new Set([...css.matchAll(/\.([A-Za-z0-9_-]+)/g)].map((mm) => mm[1]));
const allow = new Set(["copy-code", "tname", "mid", "tag", "check", "hint-mini", "s-main", "rm", "msg-inner", "false", "true", "null"]);
const clean = [...jsClasses].filter((c) => /^[A-Za-z][A-Za-z0-9_-]*$/.test(c) && !c.startsWith("md"));
const missingCss = clean.filter((c) => !cssClasses.has(c) && !allow.has(c));
if (missingCss.length) {
  problems += missingCss.length;
  console.log("MISSING CSS CLASSES:", missingCss.join(", "));
} else {
  console.log("PASS every literal JS/HTML class has a stylesheet rule");
}

console.log(problems ? "\n" + problems + " wiring problems" : "\nwiring OK");
process.exit(problems ? 1 : 0);
